def _strip_python_fence(source: str) -> str:
    """Remove a surrounding Markdown code fence from generated Python, if present."""
    match = re.search(r"```(?:python|py)?\s*\r?\n(.*?)\r?\n```", source, flags=re.IGNORECASE | re.DOTALL)
    return match.group(1).strip() if match else source.strip()


def _finalize_generated_project(
    output_directory: Path,
    project_name: str,
    tasks: list,
    process_mode: str,
) -> tuple[list[str], list[str]]:
    """Add run metadata, normalize generated code, and check the deliverables."""
    output_directory.mkdir(parents=True, exist_ok=True)

    for task in tasks:
        output_file = Path(task.output_file) if task.output_file else None
        if output_file is None:
            continue
        task_output = getattr(task, "output", None)
        raw_output = getattr(task_output, "raw", task_output) if task_output is not None else ""
        if not output_file.is_file() and raw_output:
            output_file.parent.mkdir(parents=True, exist_ok=True)
            output_file.write_text(str(raw_output), encoding="utf-8")
        if output_file.is_file() and output_file.suffix == ".py":
            code = _strip_python_fence(output_file.read_text(encoding="utf-8"))
            output_file.write_text(code + "\n", encoding="utf-8")

    safe_name = re.sub(r"[^a-z0-9]+", "-", project_name.casefold()).strip("-")[:48] or "generated-app"
    display_name = " ".join(project_name.split()) or "Generated application"
    (output_directory / "requirements.txt").write_text("gradio>=5.0\n", encoding="utf-8")
    (output_directory / "pyproject.toml").write_text(
        "[project]\n"
        f'name = "{safe_name}"\n'
        'version = "0.1.0"\n'
        'description = "Generated application"\n'
        'requires-python = ">=3.10"\n'
        'dependencies = ["gradio>=5.0"]\n',
        encoding="utf-8",
    )
    (output_directory / "README.md").write_text(
        f"# {display_name}\n\n"
        f"Workflow mode: **{process_mode.title()}**\n\n"
        "Generated by the Northstar engineering team. All source and test files are in this folder.\n\n"
        "## Run with uv\n\n"
        "```powershell\nuv sync\nuv run python app.py\n```\n\n"
        "## Run with pip\n\n"
        "```powershell\npython -m pip install -r requirements.txt\npython app.py\n```\n\n"
        "## Run backend tests\n\n"
        "```powershell\npython -m unittest -v test_backend.py\n```\n\n"
        "The app generates the tests but does not execute generated code automatically.\n",
        encoding="utf-8",
    )

    missing_files: list[str] = []
    syntax_issues: list[str] = []
    for filename in ("design.md", "backend.py", "app.py", "test_backend.py"):
        output_file = output_directory / filename
        if not output_file.is_file() or not output_file.read_text(encoding="utf-8").strip():
            missing_files.append(filename)
        elif output_file.suffix == ".py":
            try:
                ast.parse(output_file.read_text(encoding="utf-8"), filename=filename)
            except SyntaxError as error:
                syntax_issues.append(f"{filename}:{error.lineno}: {error.msg}")

    return missing_files, syntax_issues


def _run_workflow(
    project_brief: str,
    project_name: str,
    output_directory: Path,
    process_mode: str,
) -> tuple[float, list[str], list[str]]:
    """Run one CrewAI process mode and return its elapsed time and output checks."""
    completed: set[str] = set()
    progress_events: Queue[str] = Queue()
    crew, _, tasks = build_crew(
        project_brief,
        output_directory=output_directory,
        process_mode=process_mode,
    )
    stages = [task.name for task in tasks]

    def task_progress_callback(stage: str):
        def notify(_output) -> None:
            progress_events.put(stage)

        return notify

    for stage, task in zip(stages, tasks):
        task.callback = task_progress_callback(stage)
    run_state: dict[str, object] = {}

    def run_crew() -> None:
        try:
            crew.kickoff(inputs={"project_brief": project_brief})
        except Exception as error:
            run_state["error"] = error

    worker = Thread(target=run_crew, name=f"crewai-{process_mode}-run", daemon=True)
    started_at = monotonic()
    worker.start()

    mode_label = process_mode.title()
    with st.status(f"Running {mode_label} workflow…", expanded=True) as status:
        if process_mode == "hierarchical":
            st.caption("The Engineering Lead coordinates the specialists and delegates the work.")
        else:
            st.caption("The Engineering Lead and specialists execute tasks in the defined order.")
        progress_bar = st.progress(0, text="Waiting for the first task to complete")
        activity = st.empty()

        def render_progress() -> None:
            lines = [f"{'✓' if stage in completed else '○'}  {stage}" for stage in stages]
            activity.markdown("\n\n".join(lines))

        render_progress()
        last_heartbeat = -1
        while worker.is_alive() or not progress_events.empty():
            try:
                stage = progress_events.get(timeout=0.35)
            except Empty:
                elapsed = int(monotonic() - started_at)
                heartbeat = elapsed // 10
                if heartbeat > last_heartbeat:
                    last_heartbeat = heartbeat
                    progress_bar.progress(
                        len(completed) / len(stages),
                        text=f"{len(completed)} of {len(stages)} tasks complete · {elapsed}s elapsed",
                    )
                if elapsed >= 120 and not completed:
                    activity.warning("No task has finished yet. Check the terminal for model API or quota errors.")
                continue
            if stage in stages:
                completed.add(stage)
                progress_bar.progress(
                    len(completed) / len(stages),
                    text=f"{len(completed)} of {len(stages)} tasks complete",
                )
                render_progress()
                status.update(label=f"{mode_label} workflow · {len(completed)}/{len(stages)} tasks complete")
        worker.join()

        if "error" in run_state:
            status.update(label=f"{mode_label} workflow stopped with an error", state="error")
        else:
            progress_bar.progress(1.0, text="All tasks complete")
            status.update(label=f"{mode_label} workflow complete", state="complete", expanded=False)

    if "error" in run_state:
        raise run_state["error"]

    elapsed_seconds = monotonic() - started_at
    missing_files, syntax_issues = _finalize_generated_project(
        output_directory,
        project_name,
        tasks,
        process_mode,
    )
    return elapsed_seconds, missing_files, syntax_issues



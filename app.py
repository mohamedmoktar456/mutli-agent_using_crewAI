def _strip_python_fence(source: str) -> str:
    """Remove a surrounding Markdown code fence from generated Python, if present."""
    match = re.search(r"```(?:python|py)?\s*\r?\n(.*?)\r?\n```", source, flags=re.IGNORECASE | re.DOTALL)
    return match.group(1).strip() if match else source.strip()


def _finalize_generated_project(output_directory: Path, project_name: str, tasks: list) -> tuple[Path, list[str], list[str]]:
    """Add run metadata, normalize generated code, check syntax, and package the project."""
    output_directory.mkdir(parents=True, exist_ok=True)

    for task in tasks:
        output_file = Path(task.output_file) if task.output_file else None
        if output_file is None:
            continue
        task_output = getattr(task, "output", None)
        raw_output = getattr(task_output, "raw", task_output) if task_output is not None else ""
        if not output_file.is_file() and raw_output:
            output_file.parent.mkdir(parents=True, exist_ok=True)
            output_file.write_text(str(raw_output), encoding="utf-8")
        if output_file.is_file() and output_file.suffix == ".py":
            code = _strip_python_fence(output_file.read_text(encoding="utf-8"))
            output_file.write_text(code + "\n", encoding="utf-8")

    safe_name = re.sub(r"[^a-z0-9]+", "-", project_name.casefold()).strip("-")[:48] or "generated-app"
    display_name = " ".join(project_name.split()) or "Generated application"
    (output_directory / "requirements.txt").write_text("gradio>=5.0\n", encoding="utf-8")
    (output_directory / "pyproject.toml").write_text(
        "[project]\n"
        f'name = "{safe_name}"\n'
        'version = "0.1.0"\n'
        'description = "Generated application"\n'
        'requires-python = ">=3.10"\n'
        'dependencies = ["gradio>=5.0"]\n',
        encoding="utf-8",
    )
    (output_directory / "README.md").write_text(
        f"# {display_name}\n\n"
        "Generated by the Northstar engineering team. All source and test files are in this folder.\n\n"
        "## Run with uv\n\n"
        "```powershell\nuv sync\nuv run python app.py\n```\n\n"
        "## Run with pip\n\n"
        "```powershell\npython -m pip install -r requirements.txt\npython app.py\n```\n\n"
        "## Run backend tests\n\n"
        "```powershell\npython -m unittest -v test_backend.py\n```\n\n"
        "The app generates the tests but does not execute generated code automatically.\n",
        encoding="utf-8",
    )

    missing_files: list[str] = []
    syntax_issues: list[str] = []
    for filename in ("design.md", "backend.py", "app.py", "test_backend.py"):
        output_file = output_directory / filename
        if not output_file.is_file() or not output_file.read_text(encoding="utf-8").strip():
            missing_files.append(filename)
        elif output_file.suffix == ".py":
            try:
                ast.parse(output_file.read_text(encoding="utf-8"), filename=filename)
            except SyntaxError as error:
                syntax_issues.append(f"{filename}:{error.lineno}: {error.msg}")

    archive_path = output_directory / "generated_project.zip"
    with zipfile.ZipFile(archive_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for output_file in sorted(output_directory.rglob("*")):
            if not output_file.is_file() or output_file == archive_path:
                continue
            if "__pycache__" in output_file.parts or output_file.suffix == ".pyc":
                continue
            archive.write(output_file, output_file.relative_to(output_directory).as_posix())
    return archive_path, missing_files, syntax_issues


